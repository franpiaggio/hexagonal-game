def mountain(m,x,y,r,h):
    n=32;rows=17;points=[];old=m.smooth;m.smooth=True
    for j in range(rows):
        t=j/rows;rad=(1-t)**1.12*r
        ring=[]
        for i in range(n):
            a=i*TAU/n
            ridge=1+.17*math.sin(5*a+.7)+.09*math.cos(9*a-t*3)+.05*math.sin(13*a+t*8)
            ring.append((x+math.cos(a)*rad*ridge+.16*t,y+math.sin(a)*rad*.86*ridge-.11*t,max(.005,t*h+.035*h*math.sin(a*5+t*10)*math.sin(math.pi*t))))
        points.append(ring)
    for j in range(rows-1):
        for i in range(n):
            k=(i+1)%n;a=i*TAU/n;t=(j+.5)/rows
            snowline=.65+.065*math.sin(a*4+.5)+.04*math.sin(a*7)
            col='snow' if t>snowline else tint('stone',1+.08*math.sin(a*4)+.03*math.sin(j))
            m.face([points[j][i],points[j][k],points[j+1][k],points[j+1][i]],col)
    tip=(x+.16,y-.11,h)
    for i in range(n):m.face([points[-1][i],points[-1][(i+1)%n],tip],'snow')
    m.smooth=old

def rock(m,x,y,s=.13):
    old=m.smooth;m.smooth=True;n=16;rings=[]
    for z,r in [(0,.8),(.28,1),(.66,.87),(.91,.4)]:
        rings.append([(x+math.cos(i*TAU/n)*s*r*(1+.08*math.sin(i*3)),y+math.sin(i*TAU/n)*s*r*.8,.006+z*s) for i in range(n)])
    for j in range(3):
        for i in range(n):
            k=(i+1)%n;m.face([rings[j][i],rings[j][k],rings[j+1][k],rings[j+1][i]],'stone')
    m.face(rings[-1],'stone');m.smooth=old

