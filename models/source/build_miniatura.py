def patch(m,x,y,rx,ry,color,z=.006,n=11):
    # Remove the old flat grass islands; texture now carries the variation.
    if z==.006 and color!='sand':return
    if color in ('water_light','water_dark'):return
    count=m.patch_layers.get(z,0)+1;m.patch_layers[z]=count
    z+=count*.00015
    pts=[]
    for i in range(60):
        a=i*TAU/60
        f=1+.024*math.sin(3*a+.3)+.018*math.cos(7*a-.4)
        pts.append((x+rx*math.cos(a)*f,y+ry*math.sin(a)*f))
    m.polygon(pts,z,color)

