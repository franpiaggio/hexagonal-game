def category(color):
    if not isinstance(color,str):
        color=min(PALETTE,key=lambda k:sum((a-b)**2 for a,b in zip(rgb(k),color)))
    if color.startswith(('water','foam')):return WATER
    if color.startswith(('wood','trunk')):return TIMBER
    if color.startswith(('stone','snow','plaster','window','glass')):return STONE
    if color.startswith(('roof','slate')):return METAL
    return SOIL

OldMesh=Mesh
class Mesh(OldMesh):
    def __init__(self,seed):
        super().__init__(seed);self.uv=[];self.material_indices=[];self.smooth_faces=[];self.forced_material=None;self.smooth=False
    def face(self,vertices,color,jitter=0):
        slot=self.forced_material if self.forced_material is not None else category(color)
        super().face(vertices,color,jitter)
        # Dominant-plane UV projection gives real grain to all opaque surfaces.
        points=[Vector(v) for v in vertices];normal=(points[1]-points[0]).cross(points[2]-points[0])
        axis=max(range(3),key=lambda k:abs(normal[k]));dims=[k for k in range(3) if k!=axis]
        scale=1.8 if slot==SOIL else 2.5
        self.uv.append([(p[dims[0]]*scale,p[dims[1]]*scale) for p in points])
        self.material_indices.append(slot);self.smooth_faces.append(self.smooth)
    def tube(self,*args,**kwargs):
        old=self.smooth;self.smooth=True
        super().tube(*args,**kwargs)
        self.smooth=old
    def finish(self,name,collection):
        obj=super().finish(name,collection);data=obj.data
        data.materials.clear()
        for m in materials:data.materials.append(m)
        uv=data.uv_layers.new(name='UVMap')
        for poly,coords,slot,smooth in zip(data.polygons,self.uv,self.material_indices,self.smooth_faces):
            poly.material_index=slot;poly.use_smooth=smooth
            for loop,co in zip(poly.loop_indices,coords):uv.data[loop].uv=co
        bm=bmesh.new();bm.from_mesh(data)
        bmesh.ops.remove_doubles(bm,verts=list(bm.verts),dist=.000001)
        bmesh.ops.triangulate(bm,faces=list(bm.faces))
        bm.to_mesh(data);bm.free();data.update()
        return obj

def foliage(m,start,end,width,kind=PINE,roll=0):
    start=Vector(start);end=Vector(end);direction=(end-start).normalized()
    side=direction.cross(Vector((0,0,1)))
    if side.length<.01:side=Vector((1,0,0))
    side.normalize();other=direction.cross(side).normalized()
    across=(side*math.cos(roll)+other*math.sin(roll))*width/2
    old=m.forced_material;m.forced_material=kind
    tint_value=m.rng.uniform(.83,1.19)
    for i in range(2):
        t=i/2;t2=(i+1)/2
        p=start.lerp(end,t);q=start.lerp(end,t2)
        sag=(end-start).length*.09
        p.z-=math.sin(t*math.pi)*sag;q.z-=math.sin(t2*math.pi)*sag
        m.face([tuple(p-across),tuple(q-across),tuple(q+across),tuple(p+across)],(tint_value,)*3)
        m.uv[-1]=[(0,t),(0,t2),(1,t2),(1,t)]
    m.forced_material=old

def pine(m,x,y,h=1):
    tilt=Vector((m.rng.uniform(-.04,.04)*h,m.rng.uniform(-.04,.04)*h,0))
    m.tube((x,y,0),(x+tilt.x,y+tilt.y,h),.0105*h,'trunk',8,.002*h)
    for level in range(8):
        t=level/8;z=(.19+.76*t)*h;radius=.18*h*(1-t)**.78
        count=7 if level<5 else 5
        phase=m.rng.uniform(0,TAU)
        for i in range(count):
            a=i*TAU/count+phase+m.rng.uniform(-.18,.18)
            direction=Vector((math.cos(a),math.sin(a),0))
            origin=Vector((x+tilt.x*t,y+tilt.y*t,z+m.rng.uniform(-.024,.024)*h))
            length=radius*m.rng.uniform(.81,1.18)
            tip=origin+direction*length;tip.z+=(-.018+.045*t)*h
            m.tube(tuple(origin),tuple(tip),.0038*h*(1-t)+.0006,'trunk',5,.001)
            foliage(m,origin-direction*.015*h,tip+direction*.04*h,length*.95,PINE,m.rng.uniform(-.3,.3))
            foliage(m,origin,tip+direction*.035*h,length*.7,PINE,.95)
            if level<6:
                for sign in [-1,1]:
                    branch=origin.lerp(tip,.47)
                    angle=a+sign*.65
                    end=branch+Vector((math.cos(angle),math.sin(angle),.12))*length*.64
                    foliage(m,branch,end,length*.7,PINE,sign*.36)
    foliage(m,(x-.01,y,h*.82),(x+tilt.x,y+tilt.y,h*1.06),h*.11,PINE,.3)
    foliage(m,(x-.01,y,h*.82),(x+tilt.x,y+tilt.y,h*1.06),h*.11,PINE,1.8)

def lenga(m,x,y,h=.85):
    m.tube((x,y,0),(x+.03*h,y,h*.84),.025*h,'trunk',8,.006*h)
    for i in range(15):
        a=i*2.39996+m.rng.uniform(-.2,.2)
        z=m.rng.uniform(.45,.82)*h
        root=Vector((x,y,z*.65));reach=m.rng.uniform(.13,.26)*h
        tip=Vector((x+math.cos(a)*reach,y+math.sin(a)*reach,z))
        m.tube(root,tip,.008*h,'trunk',6,.002*h)
        for j in range(3):
            theta=a+(j-1)*.8
            end=tip+Vector((math.cos(theta)*.17*h,math.sin(theta)*.17*h,.15*h))
            foliage(m,tip-Vector((0,0,.07*h)),end,.34*h,LEAF,(j-1)*.65)

